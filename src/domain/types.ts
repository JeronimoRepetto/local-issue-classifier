/**
 * Working state for a new analysis. The export options are seeded from the
 * user's `prefs.defaultExportOptions` (§3 comment on Preferences); the
 * filter, table sort and priority weights start from their own defaults.
 */
export function defaultWorkingState(prefs: Preferences): AnalysisWorkingState {
  return {
    filter: defaultFilter(),
    tableSort: defaultTableSort(),
    exportOptions: cloneExportOptions(prefs.defaultExportOptions),
    priorityWeights: defaultPriorityWeights(),
    dismissed: [],
    showDismissed: false,
    expandedIssue: null,
    visibleColumns: [...DEFAULT_VISIBLE_COLUMNS],
  }
}

export interface DefaultAnalysisParams {
  id: string
  repo: Repo
  stateFilter: Analysis['stateFilter']
  now: string // ISO 8601, injected — domain code never reads the real clock
  prefs: Preferences
}

export function defaultAnalysis(params: DefaultAnalysisParams): Analysis {
  const { id, repo, stateFilter, now, prefs } = params
  return {
    schemaVersion: 1,
    id,
    name: `${repo.fullName} (${stateFilter})`,
    repo,
    stateFilter,
    createdAt: now,
    updatedAt: now,
    fetchedAt: now,
    commentsFetched: false,
    projectContext: defaultProjectContext(repo.fullName),
    rows: [],
    working: defaultWorkingState(prefs),
  }
}
