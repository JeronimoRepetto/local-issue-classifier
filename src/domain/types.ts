// ── Factories ──────────────────────────────────────────────────────────
// Every defaultX() returns a fresh object (and fresh nested arrays/objects)
// on each call: mutating one result must never affect another.

export function defaultSecrets(): Secrets {
  return {
    jevApiKey: '',
    githubToken: '',
  }
}

/**
 * The default export order: Criticality desc → Relevance desc → Effort asc
 * (§2.6). Shared by defaultExportOptions() and defaultTableSort() — each
 * call below returns its own fresh array, never a shared reference.
 */
function defaultSortOrder(): ExportOrder {
  return [
    { key: 'criticality', direction: 'desc' },
    { key: 'relevance', direction: 'desc' },
    { key: 'effort', direction: 'asc' },
  ]
}

export function defaultTableSort(): ExportOrder {
  return defaultSortOrder()
}

export function defaultExportOptions(): ExportOptions {
  return {
    order: defaultSortOrder(),
    // FB export: mirror the table by default so the export can never show a
    // different row set/order than what the user is looking at (§2.6).
    orderMode: 'table',
    // "the current filtered view (default)", §2.6.
    scope: 'filtered',
    includeUnclassified: true,
    includeDismissed: false,
    includeConfidence: true,
    includeUrls: true,
    format: 'text',
    includeBodies: false,
  }
}

/**
 * Tolerant read of a possibly-older stored `ExportOptions` (same pattern as
 * `domain/columns.ts`'s `resolveVisibleColumns`): an analysis saved before
 * `orderMode`, `format` or `includeBodies` existed is missing those fields (or
 * `format` may hold an since-removed value), so each falls back to its default
 * rather than passing through `undefined`/unrecognized. Everything else is
 * passed through as-is.
 */
export function resolveExportOptions(stored: ExportOptions | undefined): ExportOptions {
  if (!stored) return defaultExportOptions()
  const orderMode = stored.orderMode === 'table' || stored.orderMode === 'custom' ? stored.orderMode : 'table'
  const format: ExportFormat =
    stored.format === 'markdown' || stored.format === 'html' || stored.format === 'text' ? stored.format : 'text'
  const includeBodies = typeof stored.includeBodies === 'boolean' ? stored.includeBodies : false
  return { ...stored, orderMode, format, includeBodies }
}

